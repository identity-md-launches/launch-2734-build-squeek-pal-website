const tables: Record<Lang, Record<Key, string>> = { en, vi };

export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const s = tables[lang]?.[key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

export function fmtNum(lang: Lang, n: number, digits = 0): string {
  return n.toLocaleString(lang === "vi" ? "vi-VN" : "en-US", { maximumFractionDigits: digits });
}
